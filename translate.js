// 2. الدالة المسؤولة عن تغيير اللغة
function setLanguage(lang) {
    // تغيير لغة واتجاه الصفحة (HTML tag)
    const htmlTag = document.documentElement;
    htmlTag.lang = lang; // ar, en, es
    htmlTag.dir = lang === 'ar' ? 'rtl' : 'ltr'; // rtl for Arabic, ltr otherwise

    // الحصول على كل العناصر التي تحتاج ترجمة
    const elementsToTranslate = document.querySelectorAll('[data-translate-key]');

    // المرور على العناصر وتغيير محتواها
    elementsToTranslate.forEach(element => {
        const key = element.getAttribute('data-translate-key');
        if (translations[lang] && translations[lang][key]) {
            element.textContent = translations[lang][key];
        } else {
            // (اختياري) لو لم نجد ترجمة، نرجع للنص العربي الأصلي
            element.textContent = translations['ar'][key] || element.textContent;
        }
    });

    // (اختياري) تمييز الزر النشط
    updateActiveButton(lang);

    // (اختياري) حفظ اللغة المختارة للمرات القادمة
    localStorage.setItem('preferredLanguage', lang);
}

// 3. (اختياري) دالة لتحديث الزر النشط بصرياً
function updateActiveButton(activeLang) {
    const buttons = document.querySelectorAll('.language-switcher .lang-btn');
    buttons.forEach(button => {
        if (button.textContent.toLowerCase().includes(activeLang) || (activeLang === 'ar' && button.textContent === 'العربية')) {
            button.classList.add('active');
        } else {
            button.classList.remove('active');
        }
    });
     // تعديل بسيط للتعرف على الزر العربي
    buttons.forEach(button => {
        if (button.getAttribute('onclick') === `setLanguage('${activeLang}')`) {
             button.classList.add('active');
        } else {
            button.classList.remove('active');
        }
    });
}


// 4. (اختياري) عند تحميل الصفحة، تحقق من وجود لغة محفوظة
document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('preferredLanguage');
    if (savedLang) {
        setLanguage(savedLang);
    } else {
        // إذا لا توجد لغة محفوظة، اجعل العربية هي الافتراضية ونشط زرها
        setLanguage('ar'); 
    }
});

