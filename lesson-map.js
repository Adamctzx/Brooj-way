// ---------------------------------------------------------------------
// فكّ رمز الدرس: Islamic_G9_T1_U1_L1
// ---------------------------------------------------------------------
export function decodeLessonId(lessonId) {
    const empty = { valid:false, grade:null, term:null, unit:null, lesson:null, name:null, raw:lessonId };
    if (!lessonId || typeof lessonId !== 'string') return empty;

    const parts = lessonId.replace(/^Islamic_/, '').split('_');
    if (parts.length < 4) return empty;

    const [grade, term, unit, lesson] = parts;
    let name = null;
    try {
        name = LESSON_MAP[grade][term][unit][lesson] || null;
    } catch (e) { name = null; }

    return {
        valid: true,
        grade, term, unit, lesson,
        name: name && name.trim() ? name.trim() : null,
        gradeLabel: GRADE_LABELS[grade] || grade,
        termLabel:  TERM_LABELS[term] || term,
        raw: lessonId
    };
}

// ---------------------------------------------------------------------
// عنوان معروض للدرس، مع بدائل معقولة إن لم يكن الرمز معروفاً
// ---------------------------------------------------------------------
export function lessonTitle(lessonId) {
    const d = decodeLessonId(lessonId);
    if (!d.valid) {
        if (!lessonId || lessonId === 'درس غير محدد') return 'تقييم عام';
        return lessonId;
    }
    if (d.name) return d.name;
    return `${d.gradeLabel} — ${d.unit} / ${d.lesson}`;
}

// ---------------------------------------------------------------------
// كل دروس صف معيّن، مرتّبة، للاستخدام في خريطة التقدّم
// ---------------------------------------------------------------------
export function gradeCurriculum(grade) {
    const out = [];
    const terms = LESSON_MAP[grade];
    if (!terms) return out;

    Object.keys(terms).sort().forEach(term => {
        Object.keys(terms[term]).sort((a,b) => parseInt(a.slice(1)) - parseInt(b.slice(1))).forEach(unit => {
            const lessons = [];
            Object.keys(terms[term][unit]).sort((a,b) => parseInt(a.slice(1)) - parseInt(b.slice(1))).forEach(lesson => {
                const nm = terms[term][unit][lesson];
                if (nm && nm.trim()) {
                    lessons.push({
                        id: `Islamic_${grade}_${term}_${unit}_${lesson}`,
                        code: lesson,
                        name: nm.trim()
                    });
                }
            });
            if (lessons.length) {
                out.push({ term, termLabel: TERM_LABELS[term] || term, unit, lessons });
            }
        });
    });
    return out;
}
