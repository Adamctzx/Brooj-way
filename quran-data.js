export const SURAH_LIST = RAW.map(([num, name, ayahs, type]) => ({
    num, name, ayahs,
    type: type === 'م' ? 'مكية' : 'مدنية'
}));

// أسماء السور فقط (متوافقة مع الاستخدام القديم في ركن التسميع)
export const SURAH_NAMES = SURAH_LIST.map(s => s.name);

export function surahByNum(num) {
    const n = parseInt(num, 10);
    return SURAH_LIST.find(s => s.num === n) || null;
}

