export function trackSurahs(trackKey) {
    const t = TRACKS.find(x => x.key === trackKey);
    if (!t) return [];
    if (t.list) return t.list.map(surahByNum).filter(Boolean);
    return SURAH_LIST.filter(s => s.num >= t.from && s.num <= t.to);
}

export function trackByKey(key) {
    return TRACKS.find(t => t.key === key) || TRACKS[0];
}
